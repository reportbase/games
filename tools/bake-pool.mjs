// Plays the pool games ahead for the boards no one plays (POOL_GAMES in games.html; Nov 28: "Let's try a variety of pre pogramed pool games
// again"), the computer against itself through the page's own `bakeGame`, and writes them into games.html between its POOL_GAMES markers.
//   node tools/bake-pool.mjs [games a level, default 2]        (LIBS_DIR=path/node_modules serves three.js from there, as the tests do)
// A change to the engine, a rack or a planner is a reason to run it again: the games are flown again from each table written, so an old game
// still plays, but its shots were aimed on the old engine.
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
import { readFile, writeFile } from 'node:fs/promises';
import { extname, join, normalize, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..'), LIBS = process.env.LIBS_DIR || join(ROOT, 'node_modules');
const require = createRequire(join(ROOT, 'package.json')); const { chromium } = require('playwright');
const PER = +(process.argv[2] || 2), KEYS = ['nine', 'eight', 'one', 'bank', 'straight', 'carom', 'bowl', 'bumper'];
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.wasm': 'application/wasm', '.json': 'application/json' };
const server = createServer(async (req, res) => {
  const p = normalize(decodeURIComponent(new URL(req.url, 'http://x').pathname)).replace(/^([/\\])+/, '');
  try { const body = await readFile(join(ROOT, p || 'index.html')); res.writeHead(200, { 'Content-Type': TYPES[extname(p)] || 'application/octet-stream' }); res.end(body); }
  catch { res.writeHead(404); res.end('nf'); } });
await new Promise(ok => server.listen(0, '127.0.0.1', ok));
const browser = await chromium.launch(), page = await browser.newPage();
await page.route(u => !/^https?:\/\/(127\.0\.0\.1|localhost)[:/]/.test(u.href) && !/^(data|blob):/.test(u.href), async r => { try { await r.fulfill({ response: await r.fetch({ timeout: 20000 }) }); } catch { try { await r.abort(); } catch {} } });
await page.route(/three\.module\.min\.js/, async r => r.fulfill({ contentType: 'text/javascript', body: await readFile(join(LIBS, 'three/build/three.module.js')) }));
await page.route(/chess\.js@1\.4\.0\/\+esm/, async r => r.fulfill({ contentType: 'text/javascript', body: await readFile(join(LIBS, 'chess.js/dist/esm/chess.js')) }));
page.on('pageerror', e => console.log('page error', e.message));
await page.goto(`http://127.0.0.1:${server.address().port}/games.html`, { waitUntil: 'domcontentloaded', timeout: 120000 });
await page.waitForFunction(() => Array.isArray(window.FIELD_APPS) && window.FIELD_APPS.some(a => a.id === 'trickshots'), null, { timeout: 120000 });
const out = {};
for (const key of KEYS){
  out[key] = [];
  for (let lv = 1; lv <= 5; lv++) for (let j = 0; j < PER; j++){
    const idx = 1000 + 97 * KEYS.indexOf(key) + 13 * lv + j, seed = idx * 2654435761 % 4294967296;
    const gm = await page.evaluate(([key, idx, lv, seed]) => window.FIELD_APPS.find(a => a.id === 'trickshots')._debug.bakeGame(key, idx, lv, seed), [key, idx, lv, seed]);
    out[key].push(gm); console.log(key, 'level', lv, 'game', j, gm.s.length - 1, 'shots');
  }
}
await browser.close(); server.close();
const file = join(ROOT, 'games.html'), html = await readFile(file, 'utf8');
const re = /(\/\/ >>> generated by tools\/bake-pool\.mjs[^\n]*\n)\s*const POOL_GAMES = .*\n(\s*\/\/ <<< end of POOL_GAMES)/;
if (!re.test(html)) throw new Error('POOL_GAMES markers not found');
await writeFile(file, html.replace(re, (_, a, b) => a + '  const POOL_GAMES = ' + JSON.stringify(out) + ';\n' + b));
console.log('written', JSON.stringify(out).length, 'characters');
